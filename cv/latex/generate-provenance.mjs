#!/usr/bin/env node
import { execFileSync } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const directory = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(directory, "../..");
const outputJson = path.join(directory, "provenance.json");
const outputTex = path.join(directory, "build-meta.tex");
const knowledgeBasePath = path.join(root, "cv", "knowledge-base.json");

function git(args) {
  try {
    return execFileSync("git", args, { cwd: root, encoding: "utf8" }).trim();
  } catch {
    return "unavailable";
  }
}

function tex(value) {
  return String(value).replace(/[\\{}$&#_%~^]/g, (character) => ({
    "\\": "\\textbackslash{}",
    "{": "\\{",
    "}": "\\}",
    "$": "\\$",
    "&": "\\&",
    "#": "\\#",
    "_": "\\_",
    "%": "\\%",
    "~": "\\textasciitilde{}",
    "^": "\\textasciicircum{}"
  })[character]);
}

const knowledgeBase = JSON.parse(await readFile(knowledgeBasePath, "utf8"));
const generatedAt = new Date().toISOString();
const sessionLocator = process.env.CODEX_SESSION_LOCATOR
  ?? "/Users/uprootiny/.codex/sessions/ (active Codex session, 2026-07-22); /Users/uprootiny/.claude/projects/-Users-uprootiny-marchdown-github-io/9e52e8dd-3177-4f21-b7a0-caf0bdc4a1fc.jsonl";
const provenance = {
  project_name: knowledgeBase.project,
  repo_path: root,
  git_remote: git(["remote", "get-url", "origin"]),
  git_branch: git(["branch", "--show-current"]),
  git_commit: git(["rev-parse", "HEAD"]),
  generated_at: generatedAt,
  generator: "Codex (GPT-5) — LaTeX CV pipeline",
  session_source: "Codex API conversation; local Claude context ingestion",
  session_locator: sessionLocator,
  renderer: "Tectonic via Nix (nixpkgs#tectonic)",
  source: "cv/latex/pavel_vasilyev_cv.tex",
  factual_inputs: [
    "cv/knowledge-base.json",
    "cv/role-dossiers.json",
    "cv/technical-assets.json"
  ],
  output: "output/pdf/Pavel_Vasilyev_Fractional_AI_Systems_CV.pdf"
};

const buildMeta = `% Generated by cv/latex/generate-provenance.mjs. Do not edit.\n`
  + `\\def\\CvProjectName{${tex(provenance.project_name)}}\n`
  + `\\def\\CvGitBranch{${tex(provenance.git_branch)}}\n`
  + `\\def\\CvShortCommit{${tex(provenance.git_commit.slice(0, 12))}}\n`
  + `\\def\\CvGeneratedDate{${tex(generatedAt.slice(0, 10))}}\n`
  + `\\def\\CvManifestPath{cv/latex/provenance.json}\n`;

await Promise.all([
  writeFile(outputJson, `${JSON.stringify(provenance, null, 2)}\n`, "utf8"),
  writeFile(outputTex, buildMeta, "utf8")
]);

console.log(`Generated ${path.relative(root, outputJson)}`);
console.log(`Generated ${path.relative(root, outputTex)}`);
